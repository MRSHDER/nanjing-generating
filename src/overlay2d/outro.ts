// 位置避开三维的同心圆（画面中下部）和印章红砖（OUTRO_SEAL，默认右下）。
import { BEAT, type Frame } from '../engine/beat';
import { createStage, ease, inOut, QINHUAI, XUANWU } from './stage';

export const AIGC_DISCLOSURE = '本片画面与配乐均由 AI 编写的程序生成 · Visuals & music generated by AI-written code';

export function outroLakeOutline(): [number, number][] {
  return XUANWU.map(([horizontal, vertical]) => [150 + (horizontal - 1.6) * 260, 1040 - (vertical - 3.1) * 150]);
}

export function createOutroOverlay(fontFamily = '"Noto Sans SC", Arial, sans-serif') {
  const stage = createStage();

  function text(c: CanvasRenderingContext2D, value: string, x: number, y: number, size: number, alpha: number, weight = 900, spacing = 0) {
    if (alpha <= 0.002) return;
    c.save();
    c.globalAlpha = Math.min(1, alpha);
    c.font = `${weight} ${size}px ${fontFamily}`;
    c.textAlign = 'center';
    c.textBaseline = 'alphabetic';
    (c as unknown as { letterSpacing: string }).letterSpacing = `${spacing}px`;
    c.fillText(value, x, y);
    c.restore();
  }

  function render(frame: Frame) {
    stage.clear();
    const b = frame.lt / BEAT;
    if (frame.section !== 'outro' || !Number.isFinite(b) || b < 0 || b >= 16) return;
    const grid = stage.ctx('front', 'muted');
    const pathOf = (c: CanvasRenderingContext2D, pts: [number, number][], a: number, w: number, closed = false) => {
      if (a <= 0.002 || pts.length < 2) return;
      c.save(); c.globalAlpha = Math.min(1, a); c.lineWidth = w; c.beginPath();
      pts.forEach(([x, y], i) => (i ? c.lineTo(x, y) : c.moveTo(x, y)));
      if (closed) c.closePath();
      c.stroke(); c.restore();
    };
    const backMuted = stage.ctx('behind', 'muted');
    const d = (start: number, dur: number) => ease((b - start) / dur);
    const river: [number, number][] = QINHUAI.map(([horizontal, vertical]) => [
      320 + (horizontal + 6) * 125,
      705 - (vertical + 3.6) * 48,
    ]);
    pathOf(backMuted, river, 0.58 * d(8, 2), 1.8);
    const xw = d(8.3, 1.2);
    pathOf(backMuted, outroLakeOutline(), 0.72 * xw, 2.4, true);

    const name = inOut((b - 12) / 1);
    text(grid, '来斯南京 · 青AI的宁', 960, 990, 30, name, 500, 4);
    text(grid, AIGC_DISCLOSURE, 960, 1032, 20, b >= 12 ? 1 : 0, 500);
  }

  return { masks: stage.masks, render };
}
