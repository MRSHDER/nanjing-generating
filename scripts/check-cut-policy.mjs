import assert from 'node:assert/strict';
import { DETECTION, loadCutPolicy, meanGrayDifference, detectCuts, stripFrames } from './cut-policy.mjs';

const policy = loadCutPolicy();
assert.equal(policy.flashTimes.length, 6);
assert.equal(policy.allowed.filter(entry => entry.label.startsWith('青年镜头')).length, 10);
for (const beat of [16, 20, 21, 23, 25, 26, 28, 30, 32, 34]) assert.ok(policy.allowed.some(entry => entry.label.startsWith('青年镜头') && Math.abs(entry.time - (36 + 2 / 3 + beat * policy.beat)) < 1e-9));
assert.ok(!policy.allowed.some(entry => Math.abs(entry.time - (36 + 2 / 3 + 18 * policy.beat)) < 1e-9));
const bridgeFrames = Array.from({ length: 1360 }, (_, index) => ({ index, time: index / 30, previousTime: index ? (index - 1) / 30 : null, difference: index ? 0.5 : null }));
bridgeFrames[1300].difference = 100;
bridgeFrames[1325].difference = 100;
const bridgeCuts = detectCuts(bridgeFrames, policy);
assert.equal(bridgeCuts.anomalies.find(entry => entry.index === 1300).status, 'allowed');
assert.equal(bridgeCuts.anomalies.find(entry => entry.index === 1325).status, 'UNEXPECTED');
assert.ok(Math.abs(policy.allowed.find(entry => entry.label === '球→砖').time - 12.604166666666668) < 1e-9);
assert.equal(policy.allowed.filter(entry => entry.label.startsWith('闪回拍点')).length, 9);
assert.ok(!policy.allowed.some(entry => entry.time > 220 / 3 + 0.001 && entry.time < 250 / 3 - 0.001));
assert.ok(policy.allowed.some(entry => entry.label === '算法凝视接青年' && Math.abs(entry.time - 110 / 3) < 1e-9));
for (const time of [6.67, 13.33, 53.33, 60]) assert.ok(!policy.allowed.some(entry => Math.abs(entry.time - time) < 0.02));
assert.ok(Math.abs(policy.flashTimes[0].start - 27.708333333333336) < 1e-9);
assert.ok(Math.abs(policy.flashTimes[1].middle - 29.6875) < 1e-9);
const frames = Array.from({ length: 2700 }, (_, index) => ({ index, time: index / 30, previousTime: index ? (index - 1) / 30 : null, difference: index ? 0.3 + index % 7 * 0.03 : null }));
assert.equal(detectCuts(frames, policy).anomalies.length, 0);
frames[300].difference = meanGrayDifference(new Uint8Array(100).fill(20), new Uint8Array(100).fill(120));
frames[379].difference = 100;
frames[400].difference = 80;
frames[1920].difference = 80;
const result = detectCuts(frames, policy);
assert.equal(result.unexpectedCount, 1);
assert.equal(result.reviewedCount, 2);
assert.equal(result.allowedCount, 1);
assert.equal(result.anomalies.find(entry => entry.index === 379).status, 'allowed');
assert.equal(result.anomalies.find(entry => entry.index === 400).status, 'reviewed-continuous');
assert.equal(result.anomalies.find(entry => entry.index === 1920).status, 'reviewed-continuous');
assert.ok(Math.abs(policy.allowed.find(entry => entry.label === '红色远景字幕墙进入').time - 13.75) < 1e-9);
assert.ok(result.threshold >= DETECTION.minimumDifference);
assert.equal(stripFrames(60, 2700).length, 31);
assert.equal(stripFrames(13.33, 2700).length, 32);
assert.equal(stripFrames(0, 30).length, 16);
assert.equal(stripFrames(29 / 30, 30).at(-1), 29);
assert.throws(() => meanGrayDifference([], []));
console.log('PASS: low noise, unknown hard cuts, allowed exact cut, continuous boundary, six sourced flash windows, complete 31/32-frame strips');
